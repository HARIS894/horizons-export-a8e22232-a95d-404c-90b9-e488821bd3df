export const generateAiDraftOptions = (prompt) => {
  const normalizedPrompt = String(prompt || '').trim().toLowerCase() || 'appointment reminder';
  const starterPool = /payment|invoice|bill/.test(normalizedPrompt)
    ? ['starter-payment-reminder', 'starter-insurance-update', 'starter-care-plan-update']
    : /insurance|cashless|tpa/.test(normalizedPrompt)
      ? ['starter-insurance-update', 'starter-care-plan-update', 'starter-appointment-reminder']
      : ['starter-appointment-reminder', 'starter-doctor-visit-reminder', 'starter-care-plan-update'];

  return starterPool.map((starterId, index) => {
    const sourceTemplate = starterTemplates.find((item) => item.id === starterId) || starterTemplates[0];
    return {
      id: `ai-${index + 1}`,
      title: index === 0 ? 'Professional draft' : index === 1 ? 'Concise draft' : 'Human-friendly draft',
      description: `AI-assisted option based on ${sourceTemplate.name}.`,
      warnings: [
        'AI output is advisory only and must be reviewed by an admin.',
        'Confirm the final Meta category and variable mapping before future submission.',
      ],
      draft: cloneTemplate(sourceTemplate, {
        id: `ai-draft-${index + 1}`,
        source: TEMPLATE_SOURCE_TYPES.AI,
        localStatus: TEMPLATE_STATUSES.DRAFT,
        metaStatus: META_TEMPLATE_STATUSES.NOT_SUBMITTED,
        metaStatusLabel: 'Not submitted to Meta',
        tags: [...sourceTemplate.tags, 'AI Assisted'],
        purpose: prompt || sourceTemplate.purpose,
        approvalHistory: [buildHistory(`AI draft generated for: ${prompt || 'general request'}`, 'Now')],
        createdAt: 'Now',
        updatedAt: 'Now',
      }),
    };
  });
};