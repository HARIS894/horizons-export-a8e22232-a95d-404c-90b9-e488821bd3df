const cloneTemplate = (template, overrides = {}) => normalizeTemplate({
  ...template,
  ...overrides,
  header: overrides.header || { ...(template.header || { type: template.headerType, content: template.headerContent }) },
  variables: overrides.variables || (template.variables || []).map((variable) => ({ ...variable })),
  buttons: overrides.buttons || (template.buttons || []).map((button) => ({ ...button })),
  approvalHistory: overrides.approvalHistory || [...(template.approvalHistory || [])],
  tags: overrides.tags || [...(template.tags || [])],
  favorite: overrides.favorite ?? template.favorite,
});

