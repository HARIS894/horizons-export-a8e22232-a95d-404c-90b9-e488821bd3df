const buildVariable = (token, name, sampleValue, description) => ({
  id: `var-${token.replace(/[^\d]/g, '') || 'x'}`,
  token,
  name,
  sampleValue,
  description,
});

const buildButton = (id, type, label, value = '') => ({ id, type, label, value });

const buildHistory = (label, time, type = 'info') => ({ label, time, type });

const toLegacyCategory = (metaCategory) => {
  if (metaCategory === 'MARKETING') {
    return 'Marketing';
  }

  if (metaCategory === 'AUTHENTICATION') {
    return 'Authentication';
  }

  return 'Utility';
};

const normalizeTemplate = (template) => {
  const header = template.header || {
    type: template.headerType || 'None',
    content: template.headerContent || '',
  };
  const localStatus = template.localStatus || template.status || TEMPLATE_STATUSES.DRAFT;
  const metaStatus = template.metaStatus || META_TEMPLATE_STATUSES.NOT_SUBMITTED;
  const history = template.approvalHistory || template.history || [];

  return {
    ...template,
    internalName: template.internalName || template.name,
    internalCategory: template.internalCategory || 'Care Coordination',
    metaCategory: template.metaCategory || 'UTILITY',
    recommendedMetaCategory: template.recommendedMetaCategory || template.metaCategory || 'UTILITY',
    healthcareUseCase: template.healthcareUseCase || 'Operations update',
    purpose: template.purpose || 'Operational template draft',
    tags: template.tags || [],
    favorite: Boolean(template.favorite),
    source: template.source || TEMPLATE_SOURCE_TYPES.LOCAL,
    header,
    headerType: header.type,
    headerContent: header.content,
    localStatus,
    status: localStatus,
    metaStatus,
    metaStatusLabel: template.metaStatusLabel || String(metaStatus).replace(/_/g, ' '),
    variables: template.variables || [],
    buttons: template.buttons || [],
    approvalHistory: history,
    history: history.map((entry) => (typeof entry === 'string' ? entry : entry.label)),
    category: template.category || toLegacyCategory(template.metaCategory || 'UTILITY'),
    isHealthcareSafe: template.isHealthcareSafe !== false,
  };
};

const makeStarterTemplate = ({
  id,
  name,
  purpose,
  internalCategory,
  metaCategory,
  useCase,
  body,
  variables,
  buttons = [],
  language = 'English (India)',
  headerType = 'Text',
  headerContent = name,
  footer = 'InstantCare support desk',
  tags = [],
}) => normalizeTemplate({
  id,
  name,
  internalName: id.replace(/-/g, '_'),
  purpose,
  internalCategory,
  metaCategory,
  recommendedMetaCategory: metaCategory,
  healthcareUseCase: useCase,
  language,
  source: TEMPLATE_SOURCE_TYPES.STARTER,
  localStatus: TEMPLATE_STATUSES.READY_TO_SUBMIT,
  metaStatus: META_TEMPLATE_STATUSES.NOT_SUBMITTED,
  createdAt: 'Starter library',
  updatedAt: 'Starter library',
  submittedAt: null,
  header: { type: headerType, content: headerContent },
  body,
  footer,
  variables,
  buttons,
  tags,
  approvalHistory: [buildHistory('Starter library template prepared', 'Local only')],
});

